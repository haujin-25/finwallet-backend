CREATE TABLE transfers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference           VARCHAR(50)  NOT NULL UNIQUE,
    sender_wallet_id    BIGINT       NOT NULL,
    recipient_wallet_id BIGINT       NOT NULL,
    amount              BIGINT       NOT NULL,
    currency            VARCHAR(3)   NOT NULL,
    description         VARCHAR(500),
    status              VARCHAR(20)  NOT NULL DEFAULT 'COMPLETED',
    idempotency_key     VARCHAR(255) NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_transfers_sender_wallet    FOREIGN KEY (sender_wallet_id)    REFERENCES wallets(id),
    CONSTRAINT fk_transfers_recipient_wallet FOREIGN KEY (recipient_wallet_id) REFERENCES wallets(id),
    CONSTRAINT chk_transfers_amount          CHECK (amount > 0),
    CONSTRAINT chk_transfers_different_wallets CHECK (sender_wallet_id != recipient_wallet_id),
    CONSTRAINT chk_transfers_status          CHECK (status IN ('COMPLETED', 'FAILED')),
    CONSTRAINT uq_transfers_sender_idempotency UNIQUE (sender_wallet_id, idempotency_key)
);

CREATE INDEX idx_transfers_sender_wallet_id    ON transfers(sender_wallet_id);
CREATE INDEX idx_transfers_recipient_wallet_id ON transfers(recipient_wallet_id);
